test('desktop, tablet and mobile layouts stay within the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.goto('/')
  await page.screenshot({ path: '/tmp/astana-qa-landing.png', fullPage: true })
  await page.getByRole('button', { name: 'Начать сценарий' }).click()
  await expect(page.getByTestId('score')).toHaveText('52,56')
  await page.screenshot({ path: '/tmp/astana-qa-command.png' })
  for (const width of [1440, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
  await page.setViewportSize({ width: 1440, height: 1050 })
  await navigate(page, 'Community funding')
  await page.screenshot({ path: '/tmp/astana-qa-funding.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
